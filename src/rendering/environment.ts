export interface SkyPalette {
  top: string;
  horizon: string;
  ground: string;
  sun: string;
}

export interface EnvironmentHandles {
  sun: DirectionalLight;
  ambient: HemisphericLight;
  shadows: ShadowGenerator;
  sky: Mesh;
  setQuality(profile: 'low' | 'balanced' | 'high'): void;
  updateForTarget(position: Vector3): void;
}

const hexToColor = (hex: string): Color3 => Color3.FromHexString(hex);

/**
 * A deep, slightly hazy sky dome. The equirectangular PNG is generated by the
 * asset pipeline (tools/assetgen/textures.py) and is bundled locally.
 */
export function createSkyDome(scene: Scene, textureUrl: string, diameter = 2400): Mesh {
  const sky = MeshBuilder.CreateSphere('sky', { diameter, segments: 32, sideOrientation: Mesh.BACKSIDE }, scene);
  sky.infiniteDistance = true;
  sky.renderingGroupId = 0;
  sky.isPickable = false;

  const mat = new StandardMaterial('sky-mat', scene);
  mat.disableLighting = true;
  mat.backFaceCulling = false;
  mat.fogEnabled = false;
  mat.specularColor = Color3.Black();
  const tex = new Texture(textureUrl, scene, false, false, Texture.TRILINEAR_SAMPLINGMODE);
  tex.gammaSpace = true;
  // Babylon sphere UVs point the other way round from an equirect sky map.
  tex.vScale = -1;
  tex.vOffset = 1;
  mat.emissiveTexture = tex;
  mat.emissiveColor = new Color3(0.52, 0.60, 0.70);
  mat.diffuseColor = Color3.Black();
  sky.material = mat;
  sky.applyFog = false;
  return sky;
}

/** Soft procedural environment cube for PBR reflections (no remote assets). */
export function createProceduralEnvironment(scene: Scene, palette: SkyPalette): RawCubeTexture | null {
  try {
    const size = 32;
    const faces: ArrayBufferView[] = [];
    const top = hexToColor(palette.top);
    const horizon = hexToColor(palette.horizon);
    const ground = hexToColor(palette.ground);
    const sun = hexToColor(palette.sun);

    // Face order: +X, -X, +Y, -Y, +Z, -Z
    for (let f = 0; f < 6; f++) {
      const data = new Uint8Array(size * size * 4);
      for (let y = 0; y < size; y++) {
        for (let x = 0; x < size; x++) {
          const u = (x + 0.5) / size * 2 - 1;
          const v = (y + 0.5) / size * 2 - 1;
          let dx = 0;
          let dy = 0;
          let dz = 0;
          switch (f) {
            case 0: dx = 1; dy = -v; dz = -u; break;
            case 1: dx = -1; dy = -v; dz = u; break;
            case 2: dx = u; dy = 1; dz = v; break;
            case 3: dx = u; dy = -1; dz = -v; break;
            case 4: dx = u; dy = -v; dz = 1; break;
            default: dx = -u; dy = -v; dz = -1; break;
          }
          const len = Math.hypot(dx, dy, dz) || 1;
          const ny = dy / len;
          let r: number;
          let g: number;
          let b: number;
          if (ny >= 0) {
            const t = Math.pow(ny, 0.55);
            r = horizon.r + (top.r - horizon.r) * t;
            g = horizon.g + (top.g - horizon.g) * t;
            b = horizon.b + (top.b - horizon.b) * t;
          } else {
            const t = Math.min(1, -ny * 3.2);
            r = horizon.r + (ground.r - horizon.r) * t;
            g = horizon.g + (ground.g - horizon.g) * t;
            b = horizon.b + (ground.b - horizon.b) * t;
          }
          // A soft sun blob in +X/+Z-ish direction.
          const sunDot = Math.max(0, (dx * 0.45 + dy * 0.62 + dz * 0.64) / len);
          const glow = Math.pow(sunDot, 28) * 0.9 + Math.pow(sunDot, 6) * 0.12;
          r = r + (sun.r - r) * glow;
          g = g + (sun.g - g) * glow;
          b = b + (sun.b - b) * glow;
          const idx = (y * size + x) * 4;
          data[idx] = Math.round(Math.min(1, r) * 255);
          data[idx + 1] = Math.round(Math.min(1, g) * 255);
          data[idx + 2] = Math.round(Math.min(1, b) * 255);
          data[idx + 3] = 255;
        }
      }
      faces.push(data);
    }
    const tex = new RawCubeTexture(
      scene,
      faces,
      size,
      Constants.TEXTUREFORMAT_RGBA,
      Constants.TEXTURETYPE_UNSIGNED_BYTE,
      true,
      false,
      Texture.TRILINEAR_SAMPLINGMODE,
    );
    tex.gammaSpace = true;
    tex.level = 1;
    return tex;
  } catch (err) {
    console.warn('[env] procedural environment unavailable', err);
    return null;
  }
}

export interface EnvironmentOptions {
  skyTexture: string;
  palette: SkyPalette;
  sunDirection: Vector3;
  sunIntensity: number;
  ambientIntensity: number;
  shadowMapSize: number;
  shadowDistance: number;
  fog?: { color: string; density: number };
}

export function setupEnvironment(scene: Scene, opts: EnvironmentOptions): EnvironmentHandles {
  scene.clearColor = new Color4(0.02, 0.03, 0.035, 1);
  scene.ambientColor = new Color3(0.1, 0.11, 0.12);

  const sky = createSkyDome(scene, opts.skyTexture);
  const env = createProceduralEnvironment(scene, opts.palette);
  if (env) scene.environmentTexture = env;
  scene.environmentIntensity = 0.85;

  const ambient = new HemisphericLight('ambient', new Vector3(0, 1, 0), scene);
  ambient.intensity = opts.ambientIntensity;
  ambient.diffuse = hexToColor(opts.palette.horizon);
  ambient.groundColor = hexToColor(opts.palette.ground).scale(0.5);
  ambient.specular = Color3.Black();

  const sun = new DirectionalLight('sun', opts.sunDirection.normalize(), scene);
  sun.intensity = opts.sunIntensity;
  sun.diffuse = hexToColor(opts.palette.sun);
  sun.specular = hexToColor(opts.palette.sun).scale(0.8);
  sun.shadowMinZ = 1;
  sun.shadowMaxZ = 240;
  sun.position = new Vector3(-60, 90, -60);

  const shadows = new ShadowGenerator(opts.shadowMapSize, sun);
  shadows.usePercentageCloserFiltering = true;
  shadows.filteringQuality = ShadowGenerator.QUALITY_MEDIUM;
  shadows.bias = 0.0015;
  shadows.normalBias = 0.02;
  shadows.darkness = 0.45;
  shadows.transparencyShadow = false;

  if (opts.fog) {
    scene.fogMode = Constants.FOGMODE_EXP2;
    scene.fogColor = hexToColor(opts.fog.color);
    scene.fogDensity = opts.fog.density;
  }

  const ip = scene.imageProcessingConfiguration;
  ip.toneMappingEnabled = true;
  ip.toneMappingType = ImageProcessingConfiguration.TONEMAPPING_ACES;
  ip.exposure = 0.92;
  ip.contrast = 1.14;
  ip.vignetteEnabled = false;

  scene.skipPointerMovePicking = true;
  scene.autoClear = true;

  return {
    sun,
    ambient,
    shadows,
    sky,
    setQuality(profile) {
      const size = profile === 'high' ? 2048 : profile === 'balanced' ? 1024 : 512;
      if (shadows.mapSize !== size) {
        // Recreate the shadow map at the new resolution.
        shadows.getShadowMap()?.dispose();
        shadows.mapSize = size;
      }
      const dist = profile === 'high' ? 85 : profile === 'balanced' ? 60 : 38;
      sun.shadowMaxZ = dist * 3;
      shadows.bias = profile === 'low' ? 0.003 : 0.0015;
    },
    updateForTarget(position) {
      // Keep the shadow frustum centred on the car without moving the light.
      sun.position.set(position.x - opts.sunDirection.x * 90, position.y + 90, position.z - opts.sunDirection.z * 90);
      sun.shadowMinZ = 1;
      sun.shadowMaxZ = 260;
    },
  };
}

/** Reusable dark asphalt-like PBR material for procedural bits. */
export function createSimplePbr(
  scene: Scene,
  name: string,
  color: Color3,
  metallic = 0.05,
  roughness = 0.75,
): PBRMaterial {
  const mat = new PBRMaterial(name, scene);
  mat.albedoColor = color;
  mat.metallic = metallic;
  mat.roughness = roughness;
  return mat;
}
